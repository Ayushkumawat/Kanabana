import nodemailer from 'nodemailer';
import { findMany, loadEnv } from './store.js';

export const AUTO_NOTE = 'This message is auto-generated by Kanabana.';

let transportCache;

function transport() {
  loadEnv();
  const user = String(process.env.SMTP_USER || '').trim();
  const pass = String(process.env.SMTP_PASS || '').replace(/\s+/g, '');
  if (!user || !pass) return null;
  if (!transportCache) {
    transportCache = nodemailer.createTransport({
      host: process.env.SMTP_HOST || 'smtp.gmail.com',
      port: Number(process.env.SMTP_PORT || 587),
      secure: false,
      auth: { user, pass },
    });
  }
  return transportCache;
}

export function mailFrom() {
  loadEnv();
  return String(process.env.SMTP_FROM || process.env.SMTP_USER || '').trim();
}

export async function copyAddresses(person) {
  if (!person?.id) return [];
  const [managers, links, departments] = await Promise.all([
    findMany('users', { active: 1, manager: 1 }),
    findMany('user_departments', { user_id: person.id }),
    findMany('departments', {}),
  ]);
  const teamIds = new Set(links.map((link) => link.department_id));
  const leadIds = person.manager
    ? []
    : departments.filter((department) => teamIds.has(department.id)).map((department) => department.lead_id);
  const leads = leadIds.length ? await findMany('users', { _id: { $in: leadIds }, active: 1 }) : [];
  const seen = new Set([String(person.email || '').trim().toLowerCase()]);
  const copies = [];
  for (const user of [...managers, ...leads]) {
    const email = String(user.email || '').trim();
    const key = email.toLowerCase();
    if (!email || user.id === person.id || seen.has(key)) continue;
    seen.add(key);
    copies.push(email);
  }
  return copies;
}

export async function sendMail({ to, cc, copyFor, subject, text, html, ics }) {
  const tx = transport();
  if (!tx) {
    console.error('SMTP is not configured, so the email was not sent.');
    return false;
  }
  const from = mailFrom();
  if (!to || !from) return false;
  const copies = cc || (copyFor ? await copyAddresses(copyFor) : []);
  const toKey = String(to).trim().toLowerCase();
  const ccList = [...new Set(copies.map((email) => String(email).trim()).filter(Boolean))]
    .filter((email) => email.toLowerCase() !== toKey);
  const message = {
    from: `Kanabana <${from}>`,
    to,
    cc: ccList.length ? ccList : undefined,
    subject,
    text: `${String(text || '').trim()}\n\n${AUTO_NOTE}`,
    html: html ? `${html}<p>${AUTO_NOTE}</p>` : undefined,
  };
  if (ics) {
    message.icalEvent = {
      filename: 'invite.ics',
      method: 'REQUEST',
      content: ics,
    };
  }
  try {
    await tx.sendMail(message);
    return true;
  } catch (error) {
    console.error(`Email failed (${subject}): ${error.message}`);
    return false;
  }
}

export async function checkMail() {
  const tx = transport();
  if (!tx) {
    console.error('Set SMTP_USER and SMTP_PASS to send assignment and meeting emails.');
    return;
  }
  try {
    await tx.verify();
    console.log(`Mail is ready as ${mailFrom()}`);
  } catch (error) {
    console.error(`Mail login failed: ${error.message}`);
  }
}

function taskLines(actorName, task) {
  return [
    `${actorName} assigned you “${task.title}”.`,
    '',
    task.description?.trim() || 'No extra details.',
    '',
    `Due ${task.dueDate || task.due_date}.`,
    '',
    'Open Kanabana to see it on your board.',
  ].join('\n');
}

export async function sendAssignmentEmail(person, actor, task) {
  if (!person?.email || !actor || person.id === actor.id) return false;
  return sendMail({
    to: person.email,
    copyFor: person,
    subject: `New task: ${task.title}`,
    text: taskLines(actor.name, task),
  });
}

export async function sendOverdueEmail(person, task) {
  if (!person?.email) return false;
  const lines = [
    `“${task.title}” was due ${task.due_date} and is still open.`,
    '',
    task.description?.trim() || 'No extra details.',
    '',
    'Open Kanabana to update it.',
  ];
  return sendMail({
    to: person.email,
    copyFor: person,
    subject: `Deadline passed: ${task.title}`,
    text: lines.join('\n'),
  });
}

export async function sendDependencyEmail(person, actor, task, note) {
  if (!person?.email || !actor || person.id === actor.id) return false;
  const lines = [
    `${actor.name} is waiting on you for “${task.title}”.`,
    '',
    note?.trim() || 'No extra details.',
  ];
  if (task.description?.trim()) {
    lines.push('', 'Task details:', task.description.trim());
  }
  if (task.due_date) lines.push('', `Due ${task.due_date}.`);
  lines.push('', 'Open Kanabana to clear it when you are done.');
  return sendMail({
    to: person.email,
    copyFor: person,
    subject: `Help needed: ${task.title}`,
    text: lines.join('\n'),
  });
}
